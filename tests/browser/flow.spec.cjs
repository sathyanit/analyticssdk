const { test, expect } = require('@playwright/test');
const fs = require('node:fs');
fs.mkdirSync('artifacts', { recursive: true });

test('restaurant interactions become dashboard metrics on desktop and mobile', async ({ page, context }) => {
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/demo');
  await expect(page.getByRole('heading', { name: 'Good food. Better moments.' })).toBeVisible();
  await page.getByRole('button', { name: 'Add Harvest bowl', exact: true }).click();
  await expect(page.locator('#total')).toHaveText('$14.50');
  await page.getByRole('button', { name: 'Place demo order' }).click();
  await expect(page.locator('#order-status')).toContainText('confirmed');
  await expect(page.locator('#cart-count')).toHaveText('0 items');
  await page.screenshot({ path: 'artifacts/restaurant-desktop.png', fullPage: true });
  const dashboard = await context.newPage();
  dashboard.on('pageerror', e => errors.push(e.message));
  await dashboard.goto('/dashboard');
  await expect(dashboard.locator('#auth')).toBeVisible();
  await dashboard.getByLabel('Dashboard access token').fill('browser-test-token');
  await dashboard.getByRole('button', { name: 'Unlock dashboard' }).click();
  await expect(dashboard.locator('#auth')).toBeHidden();
  await expect(dashboard.locator('#orders')).toHaveText('1');
  await expect(dashboard.locator('#page_views')).toHaveText('1');
  await expect(dashboard.locator('#visitors')).toHaveText('1');
  await expect(dashboard.locator('#recent')).toContainText('order_created');
  await dashboard.locator('#event-filter').selectOption('order_created');
  await expect(dashboard.locator('#page_views')).toHaveText('0');
  await expect(dashboard.locator('#trend-title')).toHaveText('Event trends');
  await expect(dashboard.locator('#chart')).toHaveAttribute('aria-label', /1 orders/);
  await dashboard.locator('#event-filter').selectOption('');
  await expect(dashboard.locator('#page_views')).toHaveText('1');
  await dashboard.screenshot({ path: 'artifacts/dashboard-desktop.png', fullPage: true });
  await dashboard.setViewportSize({ width: 390, height: 844 });
  await expect(dashboard.getByRole('heading', { name: 'Analytics overview' })).toBeVisible();
  expect(await dashboard.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await dashboard.screenshot({ path: 'artifacts/dashboard-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByLabel('Allow analytics on this browser').uncheck();
  await page.getByRole('button', { name: 'Add Garden lemonade', exact: true }).click();
  await expect(page.locator('#total')).toHaveText('$5.50');
  await page.screenshot({ path: 'artifacts/restaurant-mobile.png', fullPage: true });
  expect(errors).toEqual([]);
});
